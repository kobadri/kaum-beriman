create table if not exists public.reading_materials (
  id bigint generated by default as identity primary key,
  week_number integer not null check (week_number between 1 and 12),
  section_key text not null check (section_key in ('outline', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday')),
  title text not null default '',
  content_html text not null default '',
  status text not null default 'draft' check (status in ('draft', 'ready', 'published')),
  pdf_url text,
  audio_url text,
  video_url text,
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  unique (week_number, section_key)
);

create index if not exists reading_materials_public_lookup
  on public.reading_materials (week_number, section_key)
  where status = 'published';

alter table public.reading_materials enable row level security;

-- Visitors can only read published materials.
drop policy if exists "Public can read published materials" on public.reading_materials;
create policy "Public can read published materials"
  on public.reading_materials for select
  to anon, authenticated
  using (status = 'published');

-- Editors require an administrator role in app_metadata, which ordinary users
-- cannot change for themselves.
drop policy if exists "Admins can read all materials" on public.reading_materials;
create policy "Admins can read all materials"
  on public.reading_materials for select
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can insert materials" on public.reading_materials;
create policy "Admins can insert materials"
  on public.reading_materials for insert
  to authenticated
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can update materials" on public.reading_materials;
create policy "Admins can update materials"
  on public.reading_materials for update
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete materials" on public.reading_materials;
create policy "Admins can delete materials"
  on public.reading_materials for delete
  to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant select on public.reading_materials to anon, authenticated;
grant insert, update, delete on public.reading_materials to authenticated;
grant usage, select on sequence public.reading_materials_id_seq to authenticated;

-- Public bucket for published reading attachments.
-- Only authenticated admins can upload, update or delete files.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'reading-media',
  'reading-media',
  true,
  104857600,
  array['application/pdf', 'audio/mpeg', 'audio/mp3', 'audio/mp4', 'audio/aac', 'audio/ogg', 'audio/wav', 'video/mp4', 'video/webm']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can view published media files" on storage.objects;
create policy "Anyone can view published media files"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'reading-media');

drop policy if exists "Admins can upload reading media" on storage.objects;
create policy "Admins can upload reading media"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'reading-media'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can update reading media" on storage.objects;
create policy "Admins can update reading media"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'reading-media'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  )
  with check (
    bucket_id = 'reading-media'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can delete reading media" on storage.objects;
create policy "Admins can delete reading media"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'reading-media'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );
