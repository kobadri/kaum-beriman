create table if not exists public.reading_materials (
  id bigint generated by default as identity primary key,
  week_number integer not null check (week_number between 1 and 12),
  section_key text not null check (section_key in ('outline', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday')),
  title text not null default '',
  content_html text not null default '',
  status text not null default 'draft' check (status in ('draft', 'ready', 'published')),
  pdf_url text,
  audio_url text,
  video_url text,
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  unique (week_number, section_key)
);

create index if not exists reading_materials_public_lookup
  on public.reading_materials (week_number, section_key)
  where status = 'published';

alter table public.reading_materials enable row level security;

drop policy if exists "Public can read published materials" on public.reading_materials;
create policy "Public can read published materials"
  on public.reading_materials for select to anon, authenticated
  using (status = 'published');

drop policy if exists "Admins can read all materials" on public.reading_materials;
create policy "Admins can read all materials"
  on public.reading_materials for select to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can insert materials" on public.reading_materials;
create policy "Admins can insert materials"
  on public.reading_materials for insert to authenticated
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can update materials" on public.reading_materials;
create policy "Admins can update materials"
  on public.reading_materials for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete materials" on public.reading_materials;
create policy "Admins can delete materials"
  on public.reading_materials for delete to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant select on public.reading_materials to anon, authenticated;
grant insert, update, delete on public.reading_materials to authenticated;
grant usage, select on sequence public.reading_materials_id_seq to authenticated;

create table if not exists public.reading_assets (
  id bigint generated by default as identity primary key,
  week_number integer not null check (week_number between 1 and 12),
  day_key text not null check (day_key in ('outline', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday')),
  day_label text not null,
  session_date date not null,
  asset_type text not null check (asset_type in ('text', 'audio', 'video')),
  original_name text not null,
  stored_name text not null,
  storage_path text not null unique,
  public_url text,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes >= 0 and size_bytes <= 104857600),
  status text not null default 'draft' check (status in ('draft', 'ready', 'published')),
  created_at timestamptz not null default now()
);

create index if not exists reading_assets_public_lookup
  on public.reading_assets (week_number, day_key, status, session_date);

alter table public.reading_assets enable row level security;

