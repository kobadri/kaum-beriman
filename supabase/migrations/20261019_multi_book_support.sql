-- Multi-book support for Penyegaran Pagi - FKKP.
-- Run AFTER schema.sql. Existing materials/assets are linked to the legacy book;
-- no existing rows or Storage objects are deleted.

create table if not exists public.reading_books (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  week_count integer not null check (week_count between 1 and 104),
  start_date date not null,
  status text not null default 'active' check (status in ('draft', 'active', 'archived')),
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.reading_books enable row level security;

drop policy if exists "Public can read active and archived books" on public.reading_books;
create policy "Public can read active and archived books"
  on public.reading_books for select to anon, authenticated
  using (status in ('active', 'archived'));

drop policy if exists "Admins can read all books" on public.reading_books;
create policy "Admins can read all books"
  on public.reading_books for select to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can insert books" on public.reading_books;
create policy "Admins can insert books"
  on public.reading_books for insert to authenticated
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can update books" on public.reading_books;
create policy "Admins can update books"
  on public.reading_books for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete books" on public.reading_books;
create policy "Admins can delete books"
  on public.reading_books for delete to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant select on public.reading_books to anon, authenticated;
grant insert, update, delete on public.reading_books to authenticated;
grant usage, select on sequence public.reading_books_id_seq to authenticated;

insert into public.reading_books (slug, title, week_count, start_date, status, description)
values ('kaum-beriman-1', 'Kaum Beriman (1)', 12, date '2026-10-05', 'active',
        'Program awal Penyegaran Pagi - FKKP.')
on conflict (slug) do nothing;

alter table public.reading_materials add column if not exists book_id bigint references public.reading_books(id);
alter table public.reading_assets add column if not exists book_id bigint references public.reading_books(id);

update public.reading_materials
set book_id = (select id from public.reading_books where slug = 'kaum-beriman-1')
where book_id is null;

update public.reading_assets
set book_id = (select id from public.reading_books where slug = 'kaum-beriman-1')
where book_id is null;

alter table public.reading_materials alter column book_id set not null;
alter table public.reading_assets alter column book_id set not null;

-- Replace single-book uniqueness and hard-coded 12-week limits with per-book limits.
alter table public.reading_materials drop constraint if exists reading_materials_week_number_section_key_key;
alter table public.reading_materials drop constraint if exists reading_materials_week_number_check;
alter table public.reading_materials add constraint reading_materials_week_number_check check (week_number between 1 and 104);
alter table public.reading_materials add constraint reading_materials_book_week_section_key unique (book_id, week_number, section_key);

alter table public.reading_assets drop constraint if exists reading_assets_week_number_check;
alter table public.reading_assets add constraint reading_assets_week_number_check check (week_number between 1 and 104);

create index if not exists reading_materials_book_lookup
  on public.reading_materials (book_id, week_number, section_key);

create index if not exists reading_assets_book_lookup
  on public.reading_assets (book_id, week_number, day_key, status, session_date);

